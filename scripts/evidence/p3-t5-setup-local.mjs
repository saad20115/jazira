import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

/**
 * Local-only setup for `P3-T5` evidence runs (`handoff/tasks/P3-T5.md` E1/E3).
 *
 * Against the `p3t5` dev database seeded by `pnpm seed`, it:
 *   1. registers the first admin on an empty users table (test credentials are generated once and
 *      kept in the git-ignored `.env` as `P3T5_ADMIN_EMAIL` / `P3T5_ADMIN_PASSWORD`; never printed);
 *   2. publishes the seeded `home-page` draft in `en` and `ar` exactly as seeded;
 *   3. switches `site-settings.arabicEnabled` on, so `/ar` renders (the "switch on" state).
 *
 * Usage:
 *   node scripts/evidence/p3-t5-setup-local.mjs [baseUrl=http://localhost:3170]
 */

const ENV_PATH = path.resolve(process.cwd(), '.env')
const LOCALES = ['en', 'ar']
const STRIP_KEYS = new Set(['id', 'createdAt', 'updatedAt', 'globalType', '_status'])

function readEnvValue(key) {
  if (!fs.existsSync(ENV_PATH)) {
    return undefined
  }
  for (const rawLine of fs.readFileSync(ENV_PATH, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim()
    if (line.startsWith(`${key}=`)) {
      return line.slice(key.length + 1)
    }
  }
  return undefined
}

function ensureAdminCredentials() {
  const email = readEnvValue('P3T5_ADMIN_EMAIL')
  const password = readEnvValue('P3T5_ADMIN_PASSWORD')
  if (email && password) {
    return { email, password }
  }
  const generated = {
    email: `p3t5-admin-${crypto.randomBytes(4).toString('hex')}@example.test`,
    password: `${crypto.randomBytes(24).toString('base64url')}Aa1!`,
  }
  fs.appendFileSync(
    ENV_PATH,
    `\n# P3-T5 local evidence admin (generated by scripts/evidence/p3-t5-setup-local.mjs)\nP3T5_ADMIN_EMAIL=${generated.email}\nP3T5_ADMIN_PASSWORD=${generated.password}\n`,
  )
  return generated
}

async function requestJson(url, init) {
  const res = await fetch(url, init)
  const text = await res.text()
  let json = null
  try {
    json = JSON.parse(text)
  } catch {
    json = null
  }
  return { status: res.status, ok: res.ok, json }
}

async function login(baseUrl, credentials) {
  const res = await requestJson(`${baseUrl}/api/users/login`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify(credentials),
  })
  return res.ok && typeof res.json?.token === 'string' ? res.json.token : null
}

async function ensureAdminToken(baseUrl) {
  const credentials = ensureAdminCredentials()
  const existing = await login(baseUrl, credentials)
  if (existing) {
    return existing
  }
  const register = await requestJson(`${baseUrl}/api/users/first-register`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ ...credentials, name: 'P3-T5 Local Evidence Admin' }),
  })
  if (!register.ok) {
    throw new Error(`first-register failed: HTTP ${String(register.status)}`)
  }
  const token = await login(baseUrl, credentials)
  if (!token) {
    throw new Error('Login after first-register failed')
  }
  return token
}

function stripMeta(doc) {
  return Object.fromEntries(Object.entries(doc).filter(([key]) => !STRIP_KEYS.has(key)))
}

async function main() {
  const baseUrl = (process.argv[2] ?? 'http://localhost:3170').replace(/\/$/, '')
  const token = await ensureAdminToken(baseUrl)
  const authHeaders = { Authorization: `JWT ${token}`, 'content-type': 'application/json' }

  for (const locale of LOCALES) {
    const draft = await requestJson(
      `${baseUrl}/api/globals/home-page?locale=${locale}&draft=true&depth=0&fallback-locale=none`,
      { headers: authHeaders },
    )
    if (!draft.ok || !draft.json) {
      throw new Error(`Reading home-page draft (${locale}) failed: HTTP ${String(draft.status)}`)
    }
    const publish = await requestJson(`${baseUrl}/api/globals/home-page?locale=${locale}`, {
      method: 'POST',
      headers: authHeaders,
      body: JSON.stringify({ ...stripMeta(draft.json), _status: 'published' }),
    })
    if (!publish.ok) {
      throw new Error(`Publishing home-page (${locale}) failed: HTTP ${String(publish.status)}`)
    }
    process.stdout.write(`home-page ${locale}: published (HTTP ${String(publish.status)})\n`)
  }

  const settings = await requestJson(`${baseUrl}/api/globals/site-settings`, {
    method: 'POST',
    headers: authHeaders,
    body: JSON.stringify({ arabicEnabled: true }),
  })
  if (!settings.ok || settings.json?.result?.arabicEnabled !== true) {
    throw new Error(`Switching arabicEnabled on failed: HTTP ${String(settings.status)}`)
  }
  process.stdout.write('site-settings: arabicEnabled=true\n')
}

await main()
